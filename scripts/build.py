#!/usr/bin/env python3
"""Build the single-file Roblox loader target using only the Python standard library."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true", help="Fail if the committed bundle is stale")
args = parser.parse_args()
core = (ROOT / "src/Core.luau").read_text()
hub = (ROOT / "src/Hub.luau").read_text()
output = "-- Generated by scripts/build.py. Edit src/*.luau, then rebuild.\n"
output += "local Core = (function()\n" + core + "\nend)()\n\n" + hub
path = ROOT / "SpeedstersBeyond.lua"
if args.check:
    if not path.exists() or path.read_text() != output:
        raise SystemExit("SpeedstersBeyond.lua is stale; run python3 scripts/build.py")
    print("Bundle is current")
else:
    path.write_text(output)
    print(f"Built {path.name}")
